#include <iostream>
#include <vector>

// Item 54：让自己熟悉标准库，包括 TR1。
// Effective C++ 第三版写作时 TR1 是扩展库；今天其中大量设施已进入 C++11/14 标准库。
// 例子使用 vector、algorithm 风格的库对象，而不是重复实现通用容器。
int main() {
    std::vector<int> scores{60, 75, 90};
    int sum = 0;
    for (int score : scores) sum += score;
    std::cout << "平均分=" << sum / static_cast<int>(scores.size()) << '\n';
    // 查阅标准库优先于自造轮子；项目还应确认目标编译器的库支持。
}
