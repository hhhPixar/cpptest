// C++11 后许多 TR1 组件迁入 std 命名空间，名称和细节仍可能有差别。
// 写业务前先搜索标准库，往往能获得已验证的语义和更好的互操作性。
// vector 管理连续动态数组，其析构会自动释放内部储存，符合 RAII。
// range-for 是 C++11 语法，这里以 C++14 编译以保持项目统一。
// static_cast 明确了 size_t 到 int 的窄化意图；实际代码要先确认范围安全。
// 如果 scores 可能为空，真实程序还应定义平均值的业务规则，避免除零。
// 本例的最小目标是展示“优先了解库”，而非建立完整评分系统。
// 标准库文档会说明复杂度、异常保证和失效规则，使用前应一并阅读。
